"""
STEP 2 — Nexus. The code leaves the machine.

Takes what step 1 wrote, authenticates to GitHub through Nexus, and pushes it
to a new branch with a pull request open on it. Every call is printed as it
goes out, and none of them ever holds a token.

    python push_and_open_pr.py
"""
import asyncio

from agents import CodeSmith
from config import BASE_BRANCH, BRANCH, TARGET_PATH, repo_slug
from runner import (banner, build_mesh, commit_file, connect, create_branch, link,
                    load, ok, open_pr, save, stage, GREEN, OFF)

PR_BODY = f"""Generated by **CodeSmith** during the JarvisCore build-along.

This module has deliberate defects in it. Inspector reviews it in step 3 and
comments here with what it finds.

`{TARGET_PATH}` — do not merge.
"""


async def main():
    banner("STEP 2 — Nexus", f"{repo_slug()} · branch {BRANCH}")

    source = load("payments.py")
    ok(f"loaded {len(source)} characters from step 1")

    stage(1, "Starting the mesh")
    mesh = await build_mesh(CodeSmith)

    stage(2, "Connecting to GitHub through Nexus")
    proxy, conn = await connect(mesh, "github")
    print("  the agent holds this connection id, never a token")

    stage(3, f"Creating branch {BRANCH} from {BASE_BRANCH}")
    await create_branch(proxy, conn, BRANCH)

    stage(4, f"Committing {TARGET_PATH}")
    commit = await commit_file(
        proxy, conn, BRANCH, TARGET_PATH, source,
        "Add payments module for review",
    )

    stage(5, "Opening the pull request")
    pr = await open_pr(proxy, conn, BRANCH, "Payments module for review", PR_BODY)

    stage(6, "Live on GitHub now")
    link("file", commit["file_url"])
    link("commit", commit["commit_url"])
    link("pull request", pr["url"])

    save("push.json", {"branch": BRANCH, "pr_number": pr["number"], "pr_url": pr["url"],
                       "file_url": commit["file_url"]})
    print(f"\n  Next: {GREEN}python review_pr.py{OFF} — read it back and review it")

    await mesh.stop()


if __name__ == "__main__":
    asyncio.run(main())
